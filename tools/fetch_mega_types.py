"""Generate the battle type table from pinned PokeAPI CSVs (no runtime requests)."""
import csv
import io
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = '81d20919845b6a445969b9265aab5cec6b04cece'
RAW = f'https://raw.githubusercontent.com/PokeAPI/pokeapi/{REF}/data/v2/csv/'


def main():
    cache = ROOT / 'tools/cache/mega-types/csv-data.json'
    if cache.exists() and json.loads(cache.read_text())['commit'] == REF:
        rows = json.loads(cache.read_text())['rows']
    else:
        rows = {}
        for name in ['pokemon', 'pokemon_types', 'types']:
            req = urllib.request.Request(RAW + name + '.csv', headers={'User-Agent': 'PokeSurvivor-development'})
            data = urllib.request.urlopen(req, timeout=30).read().decode()
            rows[name] = list(csv.DictReader(io.StringIO(data)))
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps(dict(commit=REF, rows=rows)), encoding='utf-8')
    pokemon = {r['identifier']: r for r in rows['pokemon']}
    types = {r['id']: r['identifier'] for r in rows['types']}
    forms = json.loads((ROOT / 'assets/mega/manifest.json').read_text(encoding='utf-8'))['forms']
    result = {}
    for f in forms:
        if not f['available'] or not f['basicComplete']:
            continue
        name = f['name'].lower() + '-' + f['form'].lower().replace('_', '-')
        if f['dex'] == 978:
            name = 'tatsugiri-curly-mega'
        mon = pokemon[name]
        assert int(mon['species_id']) == f['dex']
        ts = sorted([r for r in rows['pokemon_types'] if r['pokemon_id'] == mon['id']], key=lambda r: int(r['slot']))
        assert 1 <= len(ts) <= 2, name
        result[f['id']] = dict(pokemon=name, id=int(mon['id']), types=[types[r['type_id']] for r in ts])
    data = dict(source='PokeAPI/pokeapi', commit=REF, forms=result)
    (ROOT / 'assets/mega/battle-types.json').write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
    js = '/* Generated by tools/fetch_mega_types.py; provenance: assets/mega/battle-types.json. */\n'
    js += 'G.MEGA_TYPES = ' + json.dumps({k:v['types'] for k,v in result.items()}, separators=(',', ':')) + ';\n'
    (ROOT / 'js/data/mega-types.js').write_text(js, encoding='utf-8')
    print(f'Generated verified type data for {len(result)} Mega forms')


if __name__ == '__main__':
    main()
