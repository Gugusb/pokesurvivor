#!/usr/bin/env python3
"""Generate all local PokeAPI evolution chains for species in pokedex.js.

The first version fetched one species and then its chain serially.  That made
the generator time out once the local dex grew beyond the original starters.
Species records are now fetched concurrently and each evolution chain is only
downloaded once.  The generated table is runtime data: the game never calls
PokeAPI.
"""
import json, re, urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / 'js/data/pokedex.js').read_text(encoding='utf-8')
dexes = {int(x) for x in re.findall(r'"dex":(\d+)', text)}
def get(url):
    req = urllib.request.Request(url, headers={'User-Agent':'pokesurvivor/1.0'})
    with urllib.request.urlopen(req, timeout=30) as r: return json.load(r)
def chain_id(species):
    url = species.get('evolution_chain', {}).get('url')
    return int(url.rstrip('/').split('/')[-1]) if url else None

def species_record(dex):
    return dex, get(f'https://pokeapi.co/api/v2/pokemon-species/{dex}')

def node_id(node):
    return int(node['species']['url'].rstrip('/').split('/')[-1])

def paths(node):
    """Return every linear path in a possibly branching chain."""
    here = [node_id(node)]
    children = node.get('evolves_to', [])
    if not children:
        return [here]
    return [here + tail for child in children for tail in paths(child)]

species = {}
with ThreadPoolExecutor(max_workers=32) as pool:
    futures = [pool.submit(species_record, dex) for dex in sorted(dexes)]
    for future in as_completed(futures):
        dex, record = future.result()
        species[dex] = record

chain_ids = {chain_id(record) for record in species.values() if chain_id(record)}
chains_raw = {}
with ThreadPoolExecutor(max_workers=32) as pool:
    futures = {pool.submit(get, f'https://pokeapi.co/api/v2/evolution-chain/{cid}'): cid for cid in sorted(chain_ids)}
    for future in as_completed(futures):
        chains_raw[futures[future]] = future.result()

chains = {}
paths_by_species = {}
for raw in chains_raw.values():
    candidates = [[dex for dex in path if dex in dexes] for path in paths(raw['chain'])]
    candidates = [list(dict.fromkeys(path)) for path in candidates if len(path) > 1]
    if not candidates:
        continue
# Keep a deterministic default path for the chain root, and retain a path for
# every branch species.  This lets a player select any evolved species while
# still starting from the shared first form (Eevee -> Jolteon, for example).
    chosen = min(candidates, key=lambda path: (-len(path), tuple(path)))
    chains[chosen[0]] = chosen
    for candidate in candidates:
        for dex in candidate:
            current = paths_by_species.get(dex)
            if current is None or (-len(candidate), tuple(candidate)) < (-len(current), tuple(current)):
                paths_by_species[dex] = candidate
    paths_by_species[chosen[0]] = chosen
out = ('/* Generated by tools/fetch_evolutions.py from PokeAPI. */\n'
       'G.EVOLUTION_CHAINS = ' + json.dumps(chains, ensure_ascii=False, separators=(',', ':')) + ';\n'
       'G.EVOLUTION_PATHS = ' + json.dumps(paths_by_species, ensure_ascii=False, separators=(',', ':')) + ';\n')
(ROOT / 'js/data/evolutions.js').write_text(out, encoding='utf-8')
print(f'{len(chains)} chains, {len(paths_by_species)} species paths')
